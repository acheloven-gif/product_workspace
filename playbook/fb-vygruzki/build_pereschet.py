def load():
    wb = openpyxl.load_workbook(SRC, read_only=True)
    apps = {}
    for sheet in ("Шорт-лист", "Под вопросом"):
        rows = list(wb[sheet].iter_rows(values_only=True))
        hdr = rows[2]
        for r in rows[3:]:
            if not r[1]:
                continue
            d = dict(zip(hdr, r))
            apps[d["Приложение"]] = dict(block=sheet, about=d["Про что приложение"], geo=d["Гео (доли стран)"],
                                         tier1=d["Доля tier-1"], jul=d["Спенд 28д, Июль"],
                                         aug=d["Спенд 28д, Август"], oct=d["Спенд 28д, Октябрь (10.10)"])
    rows = list(wb["Сводная (все строки)"].iter_rows(values_only=True))
    hdr = rows[0]
    funnels = []
    for r in rows[1:]:
        d = dict(zip(hdr, r))
        if d["Приложение (группа)"] in apps and d["Выгрузка"] == EXPORT:
            funnels.append(d)
    return apps, funnels


def num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


